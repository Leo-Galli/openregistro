#!/usr/bin/env bash
# Commit-msg guard: fail if the message contains a Co-authored-by trailer or any
# reference to Claude/Anthropic/AI-generated attribution.
set -euo pipefail

message_file="$1"

if grep -qiE "co-authored-by|generated with claude|generated by claude|claude code|anthropic" "$message_file"; then
  echo "error: commit message must not reference AI tools or contain a Co-authored-by trailer." >&2
  exit 1
fi
